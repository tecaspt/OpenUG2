/* Duplicate hashes are valid (notably track_icon); GUIDs must be unique. */
static inline int fe_identity_find(const UgFngPackage *p,const FeIdentity *key) {
 int found=-1;
 for(int i=0;i<p->nobj;i++) {
  const UgFngObject *o=&p->obj[i];
  if(o->guid!=key->guid)continue;
  if(found>=0 || o->name_hash!=key->hash || o->parent_guid!=key->parent ||
     o->type!=(uint32_t)key->type || o->res_index!=key->resource)return -1;
  found=i;
 }
 return found;
}
